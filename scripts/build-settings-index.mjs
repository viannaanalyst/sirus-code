// Builds src/lib/settings-index.ts: every Settings row (title, description, group, page) for the
// Settings search (ADR-093). Run after adding or renaming settings: node scripts/build-settings-index.mjs
import { readFileSync, writeFileSync } from "node:fs";

const files = {
  "AppearanceSettings.tsx": "appearance", "ChatBehaviorSettings.tsx": "chat", "BrowserProfilesSettings.tsx": "chat", "SavedLoginsSettings.tsx": "chat", "ComputerSettings.tsx": "computer",
  "ConnectionsSettings.tsx": "connections", "GeneralSettings.tsx": "general", "NotificationSettings.tsx": "notifications",
  "McpSettings.tsx": "mcp", "SkillsSettings.tsx": "skills", "KeybindingsSettings.tsx": "keybindings", "SettingsPanels.tsx": null,
};
const tag = /<(SettingsRow|SettingsGroup|SettingsSection)\b[^>]*?\btitle=\{t\("([^"]+)"\)\}(?:[^>]*?\bdescription=\{t\("([^"]+)"\)\})?/g;
// Rows built by small helpers: toggle("key", "Title", "Help"), boolRow(...), booleanRow(...), row("Title", "Help", …).
const helper = /\b(?:toggle|boolRow|booleanRow)\(\s*"[A-Za-z]+",\s*"([^"]+)"(?:,\s*"([^"]+)")?|\brow\(\s*"([^"]+)",\s*(?:"([^"]+)"|undefined)/g;
const entries = [];
for (const [file, fixed] of Object.entries(files)) {
  const source = readFileSync(new URL(`../src/components/settings/${file}`, import.meta.url), "utf8");
  // In SettingsPanels each page is an `if (section === "…")` block; helpers below hold advanced/provider rows.
  // A one-line `if (section === "x") return <Page />;` covers only its own line: the rows after it
  // belong to the next page (or Advanced, the fallthrough).
  const marks = [...source.matchAll(/section === "([a-z]+)"/g)].map((match) => {
    const lineEnd = source.indexOf("\n", match.index);
    const line = source.slice(source.lastIndexOf("\n", match.index) + 1, lineEnd < 0 ? undefined : lineEnd);
    return { at: match.index, id: /\)\s*return\s.*;\s*$/.test(line) ? "advanced" : match[1] };
  });
  let group = null;
  const groups = [...source.matchAll(/<SettingsGroup\b[^>]*?\btitle=\{t\("([^"]+)"\)\}/g)];
  for (const match of source.matchAll(helper)) {
    const section = fixed ?? marks.filter((mark) => mark.at < match.index).at(-1)?.id ?? "advanced";
    const title = match[1] ?? match[3];
    // NotificationSettings' toggle(key, label) only labels a switch whose row is already indexed.
    if (/^[a-z]+$/.test(title)) continue;
    entries.push({ section, title, description: match[2] ?? match[4] ?? null, group: groups.filter((item) => item.index < match.index).at(-1)?.[1] ?? null });
  }
  for (const match of source.matchAll(tag)) {
    const section = fixed ?? marks.filter((mark) => mark.at < match.index).at(-1)?.id ?? "advanced";
    if (match[1] !== "SettingsRow") { group = match[2]; if (match[1] === "SettingsSection") continue; }
    if (match[1] === "SettingsGroup") continue;
    entries.push({ section, title: match[2], description: match[3] ?? null, group });
  }
}
const unique = entries.filter((entry, index) => entries.findIndex((other) => other.section === entry.section && other.title === entry.title) === index);
writeFileSync(new URL("../src/lib/settings-index.ts", import.meta.url), `// Generated by scripts/build-settings-index.mjs — do not edit by hand.
import type { SettingsSectionId } from "@/lib/settings";

export interface SettingsIndexEntry { section: SettingsSectionId; title: string; description: string | null; group: string | null }

export const SETTINGS_INDEX: SettingsIndexEntry[] = ${JSON.stringify(unique, null, 1)};
`);
console.log(`settings index: ${unique.length} rows`);
