fn main() {
    // The Speech framework bridge links Swift concurrency; the app needs the
    // OS Swift runtime directory on its rpath when built outside Xcode.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        println!("cargo:rustc-link-arg=-Wl,-rpath,/usr/lib/swift");
    }
    #[cfg(feature = "desktop")]
    tauri_build::build();
    #[cfg(all(feature = "host", not(feature = "desktop")))]
    host_commands::generate();
}

/// The headless host's command table (ADR-131), generated from the desktop's own
/// `generate_handler![…]` list in `src/lib.rs` and each command's signature, so a
/// command added to the app reaches the host without a second list to keep.
#[cfg(all(feature = "host", not(feature = "desktop")))]
mod host_commands {
    use std::fmt::Write;
    use std::path::Path;

    /// Modules that only exist in the desktop build; their commands stay on the Mac.
    const DESKTOP_ONLY: &[&str] = &[
        "app_update",
        "browser",
        "browser_agent",
        "browser_recording",
        "devices",
        "window_reveal",
    ];

    pub fn generate() {
        println!("cargo:rerun-if-changed=src");
        let source = Path::new("src");
        let lib = std::fs::read_to_string(source.join("lib.rs")).expect("src/lib.rs");
        let start = lib
            .find("generate_handler![")
            .expect("lib.rs lists its commands in generate_handler!");
        let list = &lib[start + "generate_handler![".len()..];
        let list = &list[..list.find(']').expect("generate_handler! closes")];
        // Commands a device may never run (`remote.rs` `DENIED`) stay out of the table too.
        let remote = std::fs::read_to_string(source.join("remote.rs")).expect("src/remote.rs");
        let denied = remote
            .split_once("const DENIED: &[&str] = &[")
            .and_then(|(_, rest)| rest.split_once("];"))
            .map(|(list, _)| list)
            .expect("remote.rs keeps its DENIED list");
        let denied: Vec<&str> = denied
            .split(',')
            .map(|entry| entry.trim().trim_matches('"'))
            .filter(|entry| !entry.is_empty())
            .collect();
        let mut arms = String::new();
        let mut available = Vec::new();
        let mut unavailable = Vec::new();
        for entry in list
            .split(',')
            .map(str::trim)
            .filter(|entry| !entry.is_empty())
        {
            let (module, name) = match entry.rsplit_once("::") {
                Some((module, name)) => (Some(module), name),
                None => (None, entry),
            };
            let Some(module) = module
                .filter(|module| !DESKTOP_ONLY.contains(module))
                .filter(|_| !denied.contains(&name))
            else {
                unavailable.push(name.to_string());
                continue;
            };
            let file = source.join(format!("{}.rs", module.replace("::", "/")));
            let text = std::fs::read_to_string(&file)
                .unwrap_or_else(|_| panic!("{} for command {entry}", file.display()));
            let Some(signature) = signature(&text, name) else {
                panic!("no command `fn {name}` in {}", file.display());
            };
            match arm(module, name, &signature) {
                Some(arm) => {
                    arms.push_str(&arm);
                    available.push(name.to_string());
                }
                None => unavailable.push(name.to_string()),
            }
        }
        let mut out = String::new();
        writeln!(
            out,
            "// Generated by build.rs from src/lib.rs (ADR-131). Do not edit."
        )
        .unwrap();
        writeln!(
            out,
            "async fn generated_call(app: &AppHandle, command: &str, args: &Value) -> Result<String, Value> {{\n    match command {{\n{arms}        _ => Err(unavailable(command)),\n    }}\n}}"
        )
        .unwrap();
        writeln!(out, "pub const HOST_COMMANDS: &[&str] = &{available:?};").unwrap();
        writeln!(
            out,
            "pub const DESKTOP_COMMANDS: &[&str] = &{unavailable:?};"
        )
        .unwrap();
        let path = Path::new(&std::env::var("OUT_DIR").unwrap()).join("host_commands.rs");
        std::fs::write(path, out).unwrap();
    }

    struct Signature {
        is_async: bool,
        params: Vec<(String, String)>,
        returns: String,
    }

    /// The parameters and return type of `fn name(` declared as a command.
    fn signature(text: &str, name: &str) -> Option<Signature> {
        let needle = format!("fn {name}(");
        let mut from = 0;
        while let Some(found) = text[from..].find(&needle) {
            let at = from + found;
            from = at + needle.len();
            let before = &text[text[..at].rfind("tauri::command").unwrap_or(0)..at];
            // The attribute must sit right above this function, not an earlier one.
            if !text[..at].contains("tauri::command")
                || before.contains("\nfn ")
                || before.contains("\n}")
            {
                continue;
            }
            let line_start = text[..at].rfind('\n').map(|index| index + 1).unwrap_or(0);
            let is_async = text[line_start..at].contains("async");
            let open = at + needle.len();
            let mut depth = 1;
            let mut close = open;
            for (index, character) in text[open..].char_indices() {
                match character {
                    '(' | '<' | '[' => depth += 1,
                    ')' | '>' | ']' => depth -= 1,
                    _ => {}
                }
                if depth == 0 {
                    close = open + index;
                    break;
                }
            }
            let params = split_top(&text[open..close])
                .into_iter()
                .filter_map(|param| {
                    let (name, kind) = param.split_once(':')?;
                    let name = name.trim().trim_start_matches("mut ").trim().to_string();
                    Some((name, kind.trim().to_string()))
                })
                .collect();
            let rest = &text[close + 1..];
            let body = rest.find('{').unwrap_or(rest.len());
            let returns = rest[..body]
                .trim()
                .strip_prefix("->")
                .map(|returns| returns.trim().to_string())
                .unwrap_or_default();
            return Some(Signature {
                is_async,
                params,
                returns,
            });
        }
        None
    }

    fn split_top(text: &str) -> Vec<String> {
        let mut parts = Vec::new();
        let mut depth = 0;
        let mut current = String::new();
        for character in text.chars() {
            match character {
                '(' | '<' | '[' => depth += 1,
                ')' | '>' | ']' => depth -= 1,
                ',' if depth == 0 => {
                    parts.push(std::mem::take(&mut current));
                    continue;
                }
                _ => {}
            }
            current.push(character);
        }
        parts.push(current);
        parts
            .into_iter()
            .map(|part| part.trim().to_string())
            .filter(|part| !part.is_empty())
            .collect()
    }

    /// Tauri's argument names: `session_id` arrives as `sessionId`.
    fn camel(name: &str) -> String {
        let mut out = String::new();
        let mut upper = false;
        for character in name.trim_start_matches('_').chars() {
            if character == '_' {
                upper = true;
            } else if upper {
                out.extend(character.to_uppercase());
                upper = false;
            } else {
                out.push(character);
            }
        }
        out
    }

    fn arm(module: &str, name: &str, signature: &Signature) -> Option<String> {
        let mut args = Vec::new();
        for (param, kind) in &signature.params {
            let kind = kind.replace(' ', "");
            let base = kind.rsplit("::").next().unwrap_or(&kind).to_string();
            if base == "AppHandle" {
                args.push("app.clone()".to_string());
            } else if kind.starts_with("State<")
                || kind.starts_with("crate::runtime::State<")
                || kind.starts_with("tauri::State<")
            {
                args.push("Manager::state(app)".to_string());
            } else if kind.contains("Window")
                || kind.contains("Webview")
                || kind.contains("tauri::")
            {
                // Commands that act on the window itself are the desktop's.
                return None;
            } else {
                args.push(format!("arg(args, {:?}, {:?})?", camel(param), name));
            }
        }
        let call = format!(
            "crate::{module}::{name}({}){}",
            args.join(", "),
            if signature.is_async { ".await" } else { "" }
        );
        let returns = signature.returns.replace(' ', "");
        let reply = if returns.starts_with("Result<")
            || returns.starts_with("crate::error::Result<")
            || returns.starts_with("std::result::Result<")
            || returns.starts_with("IpcResult<")
        {
            format!("reply_result({call})")
        } else if returns.is_empty() {
            format!("{{ {call}; Ok(\"null\".into()) }}")
        } else {
            format!("reply_value({call})")
        };
        if signature.is_async {
            return Some(format!("        {name:?} => {reply},\n"));
        }
        // Tauri runs plain commands off the async runtime (on its main thread); so does the host.
        Some(format!(
            "        {name:?} => {{\n            #[allow(unused_variables)]\n            let (app, args) = (app.clone(), args.clone());\n            blocking(move || {{\n                #[allow(unused_variables)]\n                let (app, args) = (&app, &args);\n                {reply}\n            }})\n            .await\n        }}\n"
        ))
    }
}
